# In[65]:


class PPF(nn.Module):
    
    def __init__(self,layers):
        
        super().__init__()
        
        # Define the activation function
        self.activation=nn.Tanh()
        
        # Define the loss function used (MSE)
        self.mse_loss=nn.MSELoss(reduction='mean')
        
        # Linear List for data storage
        self.linears=nn.ModuleList([nn.Linear(layers[i],layers[i+1]) for i in range(len(layers)-1)])
        
        # iter for counting purpose
        self.iter=0
        
        # setting initial valuesof weight and bias
        for i in range(len(layers)-1):
            nn.init.xavier_normal_(self.linears[i].weight.data,gain=5/3) # Weights as Xavier normal
            nn.init.zeros_(self.linears[i].bias.data)                 # Bias as Zero
    
    # Forward Pass
    def forward(self,x):
        
        # Check for torch if not then convert
        if torch.is_tensor(x)!=True:
            x=torch.from_numpy(x)
        
        # Convert lower and upper limit values to torch
        u_lim=torch.from_numpy(ub).float().to(device)
        l_lim=torch.from_numpy(lb).float().to(device)
        
        # Feature scaling
        x=(x-l_lim)/(u_lim-l_lim)
        a=x.float()
        
        # u pred and p pred should be same size of the input
        u_lin=torch.cat((a[:,[0]],a[:,[1]]),1)
        p_lin=torch.cat((a[:,[0]],a[:,[1]]),1)
        
        # Forward pass loss
        for i in range(len(layers)-2):
            z1=self.linears[i](u_lin) # Linear product (Wt.X) for velocity
            z2=self.linears[i](p_lin) # Linear product (Wt.X) for pressure
            
            u_lin=self.activation(z1)  # Passing by activation function
            p_lin=self.activation(z2)  # Passing by activation function
        
        # Consider the last layer with unit activation function
        u_lin=self.linears[-1](u_lin)
        p_lin=self.linears[-1](p_lin)
        
        # predict a=[u,p]
        a=torch.cat((u_lin,p_lin),1)
        
        # return the values of [u,p]=a
        return a
    
    # Loss function of boundary and initial condition
    def loss_BC(self,x,y):
        
        # BC1 and BC2
        xy_vel=x[0:200,:]
        
        # BC3,BC4
        xy_press=x[200:,:]
        
        # Velocity=[u,p]
        velocity=self.forward(xy_vel)
        
        # u--> predicted velocity for xy_vel
        u=velocity[:,[0]]
        
        
        #xy_vel2=x[400:500,:]
        #velocity_max=self.forward(xy_vel2)
        #umax=velocity_max[:,[0]]
        
        # pressure=[u,p]
        pressure=self.forward(xy_press)
        #pressure--> pressure valeus for xy_values
        pressure=pressure[:,[3]]

        # Calculate the MSE loss
        loss_velocity_bc=self.mse_loss(u,y[0:200,[0]])
        loss_pressure_bc=self.mse_loss(pressure,y[200:,[0]])
        #loss_velocity_max=self.mse_loss(umax,y[400:500,[0]])
        
        # sum of boundary loss
        total_bc_loss=loss_velocity_bc+loss_pressure_bc
        
        return total_bc_loss
    
    # Loss function for Domain + Boundary/Initial Points (PDE Loss)
    def loss_PDE(self,xy_to_train_f):
        muh=0.1  # As per equation
        
        # Create clone
        g=xy_to_train_f.clone()
        
        # Requires grad to be true
        g.requires_grad=True
        
        # Forward pass
        up=self.forward(g)
        
        # seperate the values
        u=up[:,[0]]
        p=up[:,[3]]

        # Calculating the gradient of U and P with respect to x and y
        u_xy=autograd.grad(u,g,torch.ones([xy_to_train_f.shape[0],1]).to(device),retain_graph=True,create_graph=True)[0]
        u_x=u_xy[:,[0]]
        u_y=u_xy[:,[1]]
        
        u_xxyy=autograd.grad(u_xy,g,torch.ones(xy_to_train_f.shape).to(device),create_graph=True)[0]
        u_xx=u_xxyy[:,[0]]
        u_yy=u_xxyy[:,[1]]
        
        p_xy=autograd.grad(p,g,torch.ones([xy_to_train_f.shape[0],1]).to(device),retain_graph=True,create_graph=True)[0]
        p_x=p_xy[:,[0]]
        p_y=p_xy[:,[1]]
        
        ###########
        # Partial differential equation
        fun=p_x-muh*(u_yy) # = 0
        ###########
        
        loss_f1=self.mse_loss(fun,f_hat)
        
        # Asssumptition #
        loss_f2=self.mse_loss(p_y,f_hat)
        loss_f3=self.mse_loss(u_x,f_hat)
        #               #
        
        #loss_assumption=abs(loss_f2)+abs(loss_f3)
        
        #file1=open('Assumptions_LOSS_Plan_poiseuille_Flow.txt','a')
        #file1.write(str(abs(loss_assumption).item())+'\n')
        #file1.close()
        
        # sum of PDE loss
        return loss_f1+loss_f2+loss_f3
    
    # Loss function which calls the Loss_bc and Loss_PDE and return the sum of both
    def loss(self,x,y,xy_to_train_f):
        
        loss1=self.loss_BC(x,y) # Call the function loss_bc
        loss2=self.loss_PDE(xy_to_train_f) # call the function loss_PDE
        
        # Total_loss of PDE and Boundary loss
        Total_loss= abs(loss1) + abs(loss2)
        
        # Saving the Data
        #file1=open('BC_LOSS_Plan_poiseuille_Flow.txt','a')
        #file1.write(str(abs(loss1).item())+'\n')
        #file1.close()
        
        #file1=open('PDE_LOSS_Plan_poiseuille_Flow.txt','a')
        #file1.write(str(abs(loss2).item())+'\n')
        #file1.close()
        
        #file3=open('TOTAL_LOSS_Plan_poiseuille_Flow.txt','a')
        #file3.write(str(Total_loss.item())+'\n')
        #file3.close()
        
        # Total Loss
        return Total_loss
    
    # Closure function 
    def closure(self):
        # Considereing the zero grad after every step
        optimizer.zero_grad()
        
        # call the loss funtion
        loss=self.loss(xy_udp_train,udp_train,XY_f_train)
        
        # Backward prop
        loss.backward()
        
        # counting iterations
        self.iter+=1
        
        # print after every 100 iterations
        if self.iter%100==0:
            print(loss)
        return loss
    
    # Test function returns the predicted the velocity and pressure
    def Test(self,xy_test):
        values=self.forward(xy_test)
        values=values.detach().cpu().numpy()
        u_pred=values[:,[0]]
        #u_pred=np.reshape(u_pred,(100,100),order="F")
        p_pred=values[:,[3]]
        #p_pred=np.reshape(p_pred,(100,100),order="F")
        
        #print("p_pred",u_pred.shape)
        #print("u_pred",u_pred.shape)
        return u_pred,p_pred


